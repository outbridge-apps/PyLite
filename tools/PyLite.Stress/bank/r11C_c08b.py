import datetime as dt, zoneinfo, time
D = dt.datetime
def t(name, f):
    try:
        print(name + '=' + repr(f())[:150])
    except Exception as e:
        print(name + '!' + type(e).__name__ + ':' + str(e)[:80])
K = zoneinfo.ZoneInfo('Pacific/Kiritimati')
NY = zoneinfo.ZoneInfo('America/New_York')
t('k1', lambda: D(1, 1, 1, 12, tzinfo=dt.timezone.utc).astimezone(K))
t('k2', lambda: D(1, 1, 1, tzinfo=NY).utcoffset())
