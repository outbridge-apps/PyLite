import re
ranges = [(0x41, 0x5a), (0x61, 0x7a), (0xb5, 0xb5), (0xc0, 0xff), (0x100, 0x17f), (0x180, 0x24f), (0x370, 0x3ff),
          (0x400, 0x4ff), (0x1e00, 0x1eff), (0x1f00, 0x1fff), (0x2100, 0x214f), (0x2c00, 0x2c7f), (0xa640, 0xa69f),
          (0xa720, 0xa7ff), (0xff21, 0xff3a), (0x10a0, 0x10ff), (0x13a0, 0x13ff), (0xab70, 0xabbf), (0x1c80, 0x1c8f),
          (0x0, 0x7f), (0x0, 0xffff), (0x4b, 0x4b), (0x53, 0x53), (0x212a, 0x212a), (0x17f, 0x17f), (0x3c2, 0x3c3),
          (0xdf, 0xdf), (0x1e9e, 0x1e9e), (0x130, 0x131), (0x49, 0x49), (0x69, 0x69), (0x345, 0x345), (0x399, 0x399)]
subject = "".join(chr(c) for c in range(0x20, 0xd800)) + "".join(chr(c) for c in range(0xe000, 0x10000))
out = []
for lo, hi in ranges:
    for flags in (re.I, re.I | re.A, 0):
        cls = "[" + chr(92) + "u%04x-" % lo + chr(92) + "u%04x]" % hi
        r = re.compile(cls, flags)
        found = r.findall(subject)
        neg = re.compile("[^" + cls[1:], flags).findall(subject[:3000])
        out.append("%x-%x %d %d %d %d" % (lo, hi, flags, len(found), sum(map(ord, found)) % 1000003, len(neg)))
for line in out:
    print(line)
