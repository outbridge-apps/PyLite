t('sub_repl_U', lambda: re.sub('a', B + 'U00000041', 'a'))
t('escape_roundtrip', lambda: re.findall(re.escape(chr(0x1F600)), chr(0x1F600)))
t('many_U', lambda: len(re.findall((U(0x1F600) + '|') * 3000 + 'x', 'x' + chr(0x1F600))))
t('many_U_cls', lambda: len(re.findall('[' + ''.join(U(0x100 + i) for i in range(5000)) + ']', chr(0x150) * 10)))
t('ascii_flag', lambda: re.findall(U(0xE9), chr(0xE9) + chr(0xC9), re.I | re.A))
t('unicode_I_E9', lambda: re.findall(U(0xE9), chr(0xE9) + chr(0xC9), re.I))
t('cls_I_E9', lambda: re.findall('[' + U(0xE9) + ']', chr(0xE9) + chr(0xC9), re.I))
t('cls_rng_I_E9', lambda: re.findall('[' + U(0xE0) + '-' + U(0xE9) + ']', chr(0xC5) + chr(0xC9), re.I))
t('fullmatch', lambda: bool(re.fullmatch(U(0x1F600) + '?', '')))
t('split', lambda: re.split(U(0x1F600), 'a' + chr(0x1F600) + 'b'))
t('subn', lambda: re.subn(U(0x1F600), '-', chr(0x1F600) * 3))
