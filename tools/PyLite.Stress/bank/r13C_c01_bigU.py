import re
B = chr(92)
def U(v):
    return B + 'U' + format(v, '08x')
def u(v):
    return B + 'u' + format(v, '04x')
out = []
def t(name, f):
    try:
        r = f()
        out.append(name + '=' + repr(r)[:100])
    except Exception as e:
        out.append(name + '!' + type(e).__name__ + ':' + str(e)[:70])

t('lit', lambda: re.findall(U(0x41), 'AaA'))
t('lit_I', lambda: re.findall(U(0x41), 'AaA', re.I))
t('lit_u_I', lambda: re.findall(u(0x41), 'AaA', re.I))
t('longs_I', lambda: re.findall(U(0x17F), 'sS' + chr(0x17F), re.I))
t('longs_u_I', lambda: re.findall(u(0x17F), 'sS' + chr(0x17F), re.I))
t('kelvin_I', lambda: re.findall(U(0x212A), 'kK' + chr(0x212A), re.I))
t('kelvin_u_I', lambda: re.findall(u(0x212A), 'kK' + chr(0x212A), re.I))
t('k_to_kelvin_I', lambda: re.findall(U(0x6B), 'kK' + chr(0x212A), re.I))
t('cls_I', lambda: re.findall('[' + U(0x41) + ']', 'aA', re.I))
t('cls_u_I', lambda: re.findall('[' + u(0x41) + ']', 'aA', re.I))
t('cls_longs_I', lambda: re.findall('[' + U(0x17F) + ']', 'sS' + chr(0x17F), re.I))
t('cls_rng', lambda: re.findall('[' + U(0x61) + '-' + U(0x63) + ']', 'abcd-'))
t('cls_rng_I', lambda: re.findall('[' + U(0x61) + '-' + U(0x63) + ']', 'ABCD-', re.I))
t('cls_rng_mix', lambda: re.findall('[a-' + U(0x63) + ']', 'abcd'))
t('cls_rng_mix2', lambda: re.findall('[' + U(0x61) + '-c]', 'abcd'))
t('cls_dash', lambda: re.findall('[a' + U(0x2D) + 'c]', 'abc-'))
t('cls_rbr', lambda: re.findall('[' + U(0x5D) + ']', 'a]'))
t('cls_caret', lambda: re.findall('[' + U(0x5E) + 'a]', '^ab'))
t('cls_bs', lambda: re.findall('[' + U(0x5C) + ']', 'a' + B))
t('cls_astral', lambda: re.findall('[' + U(0x1F600) + ']', chr(0x1F600)))
t('cls_rng_astral', lambda: re.findall('[' + B + 'x80-' + U(0x10FFFF) + ']', 'a' + chr(0xE9)))
t('cls_rng_ffff', lambda: re.findall('[' + B + 'x80-' + U(0xFFFF) + ']', 'a' + chr(0xE9)))
t('cls_neg', lambda: re.findall('[^' + U(0x61) + ']', 'abc'))
t('astral', lambda: re.findall(U(0x1F600), chr(0x1F600) * 2))
t('astral_q', lambda: re.findall(U(0x1F600) + '+', chr(0x1F600) * 3 + 'x' + chr(0x1F600)))
t('astral_q2', lambda: re.findall(U(0x1F600) + '{2}', chr(0x1F600) * 5))
t('astral_lazy', lambda: re.findall(U(0x1F600) + '*?x', chr(0x1F600) * 3 + 'x'))
t('astral_poss', lambda: re.findall(U(0x1F600) + '*+', chr(0x1F600) * 3))
t('astral_I', lambda: re.findall(U(0x10400), chr(0x10428) + chr(0x10400), re.I))
t('astral_lb', lambda: re.findall('(?<=' + U(0x1F600) + ')a', chr(0x1F600) + 'a'))
t('astral_nlb', lambda: re.findall('(?<!' + U(0x1F600) + ')a', chr(0x1F600) + 'aa'))
t('astral_groups', lambda: re.compile('(' + U(0x1F600) + ')' + B + '1').groups)
t('astral_br', lambda: re.findall('(' + U(0x1F600) + ')' + B + '1', chr(0x1F600) * 2))
t('astral_span', lambda: re.search(U(0x1F600), 'ab' + chr(0x1F600)).span())
t('nul', lambda: re.findall(U(0), 'a' + chr(0) + 'b'))
t('max', lambda: re.findall(U(0x10FFFF), chr(0x10FFFF)))
t('over', lambda: re.compile(U(0x110000)))
