import re
B = chr(92)
def t(label, pat, s, flags=0, fn='findall'):
    try:
        r = getattr(re, fn)(pat, s, flags) if fn != 'sub' else re.sub(pat, '-', s, flags=flags)
        print(label, repr(r))
    except Exception as e:
        print(label, type(e).__name__, str(e)[:80])

smile = chr(0x1F600)
