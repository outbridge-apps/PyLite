using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;

namespace Outbridge.PyLite.UnicodeGen
{
    // Generates PyUnicodeNames.Tables.g.cs: the character-name database behind \N{NAME}.
    //
    // Three sources answer the same lookup, so all three are emitted: the individual names in
    // UnicodeData.txt, the aliases in NameAliases.txt (\N{NUL}) and the multi-character sequences in
    // NamedSequences.txt. Names that are just a prefix plus the code point in hex become a rule
    // instead of ~5900 rows, and the ranges UnicodeData collapses (CJK, Tangut) are rules too;
    // Hangul syllables are composed by the runtime from their jamo.
    internal static class NamesGen
    {
        private const int BlockSize = 32;       // records per binary-search checkpoint
        internal const int MinFamily = 16;       // PREFIX-<hex> names below this stay ordinary rows

        internal static void Write(string ucdDir, string outPath)
        {
            var db = new UcdNames(ucdDir);
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("//     Generated by tools/Outbridge.PyLite.UnicodeGen from the Unicode Character Database " + db.Version + ".");
            sb.AppendLine("//     Do not edit by hand: re-run the generator instead (see its README).");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("namespace Outbridge.PyLite.Syntax");
            sb.AppendLine("{");
            sb.AppendLine("    internal static partial class PyUnicodeNames");
            sb.AppendLine("    {");
            sb.AppendLine("        internal const string UnicodeVersion = \"" + db.Version + "\";");
            sb.AppendLine();
            EmitTable(sb, db);
            EmitSequences(sb, db);
            EmitFamilies(sb, db);
            sb.AppendLine("    }");
            sb.AppendLine("}");
            File.WriteAllText(outPath, sb.ToString(), new UTF8Encoding(false));
            Console.WriteLine("wrote " + outPath + " (" + new FileInfo(outPath).Length / 1024 + " KB)");
        }

        // Front coding over the sorted names: a record carries only what it does not share with its
        // predecessor. Every block starts fresh so a checkpoint can be read on its own.
        private static void EmitTable(StringBuilder sb, UcdNames db)
        {
            var bytes = new List<byte>();
            var index = new List<int>();
            string prev = "";
            int maxName = 0;
            for (int i = 0; i < db.Entries.Count; i++)
            {
                Entry e = db.Entries[i];
                bool head = i % BlockSize == 0;
                if (head)
                    index.Add(bytes.Count);
                int shared = head ? 0 : Shared(prev, e.Name);
                bytes.Add((byte)shared);
                bytes.Add((byte)(e.Name.Length - shared));
                for (int k = shared; k < e.Name.Length; k++)
                    bytes.Add((byte)e.Name[k]);
                bytes.Add((byte)(e.Value >> 16));
                bytes.Add((byte)(e.Value >> 8));
                bytes.Add((byte)e.Value);
                prev = e.Name;
                maxName = Math.Max(maxName, e.Name.Length);
            }

            sb.AppendLine("        // Front-coded records in ascending name order, packed two bytes per char:");
            sb.AppendLine("        //   [shared prefix length][suffix length][suffix ASCII][value: 3 bytes, big-endian]");
            sb.AppendLine("        // A value below 0x110000 is a code point, 0x110000 + n an index into SeqData, and 0x200000 + cp");
            sb.AppendLine("        // an ALIAS of cp (resolves, but is not the name the reverse lookup answers with). Each block of");
            sb.AppendLine("        // NameBlock records opens with prefix length 0, so NameIndex can be searched on whole names.");
            sb.AppendLine("        private const int NameCount = " + db.Entries.Count + ";");
            sb.AppendLine("        private const int NameByteCount = " + bytes.Count + ";");
            sb.AppendLine("        private const int NameBlock = " + BlockSize + ";");
            sb.AppendLine("        private const int MaxNameLength = " + maxName + ";");
            sb.AppendLine();
            sb.AppendLine("        private const string NameData =");
            Program.AppendStringLiteral(sb, Pack(bytes));
            sb.AppendLine();
            Program.EmitIntArray(sb, "NameIndex", index.ToArray());
            Console.WriteLine("Names: " + db.Entries.Count + " rows, " + bytes.Count + " bytes, "
                + index.Count + " blocks, longest name " + maxName);
        }

        private static void EmitSequences(StringBuilder sb, UcdNames db)
        {
            sb.AppendLine("        private static readonly string[] SeqData =");
            sb.AppendLine("        {");
            foreach (string s in db.Sequences)
                sb.AppendLine("            " + Program.Quote(s) + ",");
            sb.AppendLine("        };");
            sb.AppendLine();
        }

        private static void EmitFamilies(StringBuilder sb, UcdNames db)
        {
            sb.AppendLine("        // Names that are a prefix plus the code point in hex.");
            sb.AppendLine("        private static readonly string[] HexPrefix =");
            sb.AppendLine("        {");
            foreach (Family f in db.Families)
                sb.AppendLine("            \"" + f.Prefix + "\",");     // a name is printable ASCII already
            sb.AppendLine("        };");
            sb.AppendLine();
            var ranges = new List<int>();
            for (int i = 0; i < db.Families.Count; i++)
                foreach (int[] r in db.Families[i].Ranges)
                {
                    ranges.Add(i);
                    ranges.Add(r[0]);
                    ranges.Add(r[1]);
                }
            sb.AppendLine("        // { prefix index, first, last } - only these code points carry such a name.");
            Program.EmitIntArray(sb, "HexRange", ranges.ToArray());
            Console.WriteLine("Hex families: " + db.Families.Count + " prefixes, " + ranges.Count / 3 + " ranges, "
                + db.FamilyRows + " rows replaced");
        }

        private static int Shared(string a, string b)
        {
            int n = Math.Min(Math.Min(a.Length, b.Length), 255);
            int i = 0;
            while (i < n && a[i] == b[i])
                i++;
            return i;
        }

        // Two bytes per char, big-endian; an odd tail is padded and NameByteCount keeps the real end.
        private static string Pack(List<byte> bytes)
        {
            var sb = new StringBuilder((bytes.Count + 1) / 2);
            for (int i = 0; i < bytes.Count; i += 2)
            {
                int lo = i + 1 < bytes.Count ? bytes[i + 1] : 0;
                sb.Append((char)((bytes[i] << 8) | lo));
            }
            return sb.ToString();
        }
    }

    internal struct Entry
    {
        internal string Name;
        internal int Value;                     // code point; 0x110000 + index into Sequences; AliasTag + code point
    }

    internal static class Tags
    {
        internal const int AliasTag = 0x200000;   // an alias resolves like a name but is not the reverse answer
    }

    internal sealed class Family
    {
        internal string Prefix;
        internal readonly List<int[]> Ranges = new List<int[]>();
    }

    internal sealed class UcdNames
    {
        internal readonly List<Entry> Entries = new List<Entry>();
        internal readonly List<string> Sequences = new List<string>();
        internal readonly List<Family> Families = new List<Family>();
        internal readonly string Version;
        internal int FamilyRows;

        // The label UnicodeData.txt uses for a collapsed range -> the name pattern its characters take.
        // Hangul is composed from jamo by the runtime; private use and surrogates have no names.
        private static readonly Dictionary<string, string> RangeNames = new Dictionary<string, string>
        {
            { "CJK Ideograph", "CJK UNIFIED IDEOGRAPH-" },
            { "Tangut Ideograph", "TANGUT IDEOGRAPH-" },
            { "Hangul Syllable", null },
            { "Private Use", null },
            { "Low Surrogate", null },
            { "High Surrogate", null },
        };

        internal UcdNames(string dir)
        {
            Version = ReadVersion(Path.Combine(dir, "NameAliases.txt"));
            var named = new List<Entry>();
            ReadUnicodeData(Path.Combine(dir, "UnicodeData.txt"), named);
            ExtractFamilies(named);
            ReadAliases(Path.Combine(dir, "NameAliases.txt"), named);
            ReadSequences(Path.Combine(dir, "NamedSequences.txt"), named);
            named.Sort((a, b) => string.CompareOrdinal(a.Name, b.Name));
            for (int i = 1; i < named.Count; i++)
                if (named[i].Name == named[i - 1].Name)
                    throw new InvalidDataException("duplicate name " + named[i].Name);
            Entries = named;
        }

        private static string ReadVersion(string path)
        {
            string first = File.ReadLines(path).First();
            int dash = first.LastIndexOf('-');
            int dot = first.LastIndexOf(".txt", StringComparison.Ordinal);
            return dash > 0 && dot > dash ? first.Substring(dash + 1, dot - dash - 1) : "unknown";
        }

        private static int Hex(string s)
        {
            return int.Parse(s.Trim(), NumberStyles.HexNumber, CultureInfo.InvariantCulture);
        }

        private void ReadUnicodeData(string path, List<Entry> into)
        {
            int rangeFirst = -1;
            string rangePattern = null;
            foreach (string raw in File.ReadLines(path))
            {
                string[] f = raw.Split(';');
                if (f.Length < 3)
                    continue;
                int c = Hex(f[0]);
                string name = f[1];
                if (name.Length > 0 && name[0] != '<')
                {
                    Check(name);
                    into.Add(new Entry { Name = name, Value = c });
                    continue;
                }
                if (name.EndsWith(", First>", StringComparison.Ordinal))
                {
                    string label = name.Substring(1, name.Length - 9);
                    rangePattern = Pattern(label);
                    rangeFirst = c;
                }
                else if (name.EndsWith(", Last>", StringComparison.Ordinal) && rangeFirst >= 0)
                {
                    if (rangePattern != null)
                        AddFamily(rangePattern, rangeFirst, c);
                    rangeFirst = -1;
                }
            }
        }

        // The labels carry a block suffix ("CJK Ideograph Extension H"); the pattern is the same.
        private static string Pattern(string label)
        {
            foreach (var kv in RangeNames)
                if (label.StartsWith(kv.Key, StringComparison.Ordinal) || label.EndsWith(kv.Key, StringComparison.Ordinal))
                    return kv.Value;
            throw new InvalidDataException("unknown UnicodeData range label <" + label + ">");
        }

        // A name whose tail is its own code point in hex is a rule, not a row - 4 prefixes cover
        // ~5900 of them (CJK compatibility ideographs, Egyptian hieroglyphs, Nushu, Khitan).
        private void ExtractFamilies(List<Entry> named)
        {
            var groups = new Dictionary<string, List<int>>();
            foreach (Entry e in named)
            {
                string p = HexTailPrefix(e);
                if (p == null)
                    continue;
                List<int> cps;
                if (!groups.TryGetValue(p, out cps))
                    groups[p] = cps = new List<int>();
                cps.Add(e.Value);
            }
            var big = new HashSet<string>(groups.Where(g => g.Value.Count >= NamesGen.MinFamily).Select(g => g.Key));
            foreach (string p in big.OrderBy(x => x, StringComparer.Ordinal))
            {
                List<int> cps = groups[p];
                cps.Sort();
                foreach (int cp in cps)
                    AddFamily(p, cp, cp);
                FamilyRows += cps.Count;
            }
            named.RemoveAll(e => { string p = HexTailPrefix(e); return p != null && big.Contains(p); });
        }

        private static string HexTailPrefix(Entry e)
        {
            int dash = e.Name.LastIndexOf('-');
            if (dash <= 0 || dash == e.Name.Length - 1)
                return null;
            string tail = e.Name.Substring(dash + 1);
            if (tail.Length > 6)
                return null;
            foreach (char c in tail)
                if (!((c >= '0' && c <= '9') || (c >= 'A' && c <= 'F')))
                    return null;
            return Hex(tail) == e.Value ? e.Name.Substring(0, dash + 1) : null;
        }

        // Ranges are kept exact (and merged when adjacent) so an unassigned code point in a gap can
        // never be named by the rule.
        private void AddFamily(string prefix, int first, int last)
        {
            Family f = Families.FirstOrDefault(x => x.Prefix == prefix);
            if (f == null)
                Families.Add(f = new Family { Prefix = prefix });
            int[] tail = f.Ranges.Count > 0 ? f.Ranges[f.Ranges.Count - 1] : null;
            if (tail != null && first == tail[1] + 1)
                tail[1] = last;
            else
                f.Ranges.Add(new[] { first, last });
        }

        private void ReadAliases(string path, List<Entry> into)
        {
            foreach (string raw in File.ReadLines(path))
            {
                string line = Strip(raw);
                if (line.Length == 0)
                    continue;
                string[] f = line.Split(';');
                if (f.Length < 2)
                    continue;
                Check(f[1]);
                into.Add(new Entry { Name = f[1], Value = Tags.AliasTag + Hex(f[0]) });   // tagged: never the char's own name
            }
        }

        private void ReadSequences(string path, List<Entry> into)
        {
            foreach (string raw in File.ReadLines(path))
            {
                string line = Strip(raw);
                if (line.Length == 0)
                    continue;
                string[] f = line.Split(';');
                if (f.Length < 2)
                    continue;
                var sb = new StringBuilder();
                foreach (string p in f[1].Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries))
                    sb.Append(char.ConvertFromUtf32(Hex(p)));
                Check(f[0]);
                into.Add(new Entry { Name = f[0], Value = 0x110000 + Sequences.Count });
                Sequences.Add(sb.ToString());
            }
        }

        // The lookup uppercases ASCII and compares bytes, so a name outside that alphabet - or one
        // longer than a record's length byte - would be unreachable.
        private static void Check(string name)
        {
            if (name.Length == 0 || name.Length > 255)
                throw new InvalidDataException("unusable name length: " + name);
            foreach (char c in name)
                if (!((c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == ' ' || c == '-'))
                    throw new InvalidDataException("unusable character in name: " + name);
        }

        private static string Strip(string raw)
        {
            int hash = raw.IndexOf('#');
            return (hash >= 0 ? raw.Substring(0, hash) : raw).Trim();
        }
    }
}
