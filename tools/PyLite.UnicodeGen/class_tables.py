# Writes src/PyLite/Runtime/Values/Text/PyUnicodeClass.Tables.g.cs from the CPython that runs it (3.14 for
# Unicode 16.0.0): the code point ranges where str.isprintable/isalpha/isnumeric/isdigit/isdecimal answer True,
# and the canonical compositions NFC does not make although the pair decomposes into two starters.
#   python3.14 tools/PyLite.UnicodeGen/class_tables.py > src/PyLite/Runtime/Values/Text/PyUnicodeClass.Tables.g.cs
import sys
import unicodedata

CPS = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]


def ranges(pred):
    out, start, prev = [], None, None
    for c in CPS:
        if pred(chr(c)):
            if start is None:
                start = c
            elif c != prev + 1:
                out.append((start, prev))
                start = c
            prev = c
    if start is not None:
        out.append((start, prev))
    return ' '.join('%X' % a if a == b else '%X-%X' % (a, b) for a, b in out)


def exclusions():
    out = []
    for c in CPS:
        d = unicodedata.decomposition(chr(c))
        if not d or d.startswith('<'):
            continue
        parts = [int(x, 16) for x in d.split()]
        if len(parts) != 2 or unicodedata.combining(chr(c)) or unicodedata.combining(chr(parts[0])):
            continue
        if unicodedata.normalize('NFC', chr(parts[0]) + chr(parts[1])) != chr(c):
            out.append('%X' % c)
    return ' '.join(out)


consts = [
    ('PrintableRanges', ranges(str.isprintable)),
    ('AlphaRanges', ranges(str.isalpha)),
    ('NumericRanges', ranges(str.isnumeric)),
    ('DigitRanges', ranges(str.isdigit)),
    ('DecimalRanges', ranges(str.isdecimal)),
    ('CompositionExclusions', exclusions()),
]
version = '.'.join(map(str, sys.version_info[:3]))
lines = [
    '// <auto-generated>',
    '// Unicode %s string classes: the code point ranges where CPython %s\'s str.isprintable, isalpha,'
    % (unicodedata.unidata_version, version),
    '// isnumeric, isdigit and isdecimal answer True, and the %d canonical compositions CompositionExclusions.txt'
    % len(consts[-1][1].split()),
    '// excludes (singletons and non-starter decompositions are derived from PyUnicodeProps instead). Read off',
    '// CPython itself by the snippet in tools/PyLite.UnicodeGen/README.md ("String classes").',
    '// </auto-generated>',
    'namespace Outbridge.PyLite.Runtime.Values',
    '{',
    '    internal static partial class PyUnicodeClass',
    '    {',
]
for i, (name, text) in enumerate(consts):
    if i:
        lines.append('')
    lines.append('        private const string %s = "%s";' % (name, text))
lines += ['    }', '}']
sys.stdout.write('\n'.join(lines) + '\n')
