using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;

namespace Outbridge.PyLite.UnicodeGen
{
    // Generates Modules/Support/WindowsZones.g.cs from CLDR's windowsZones.xml: the IANA -> Windows time
    // zone id map behind zoneinfo.ZoneInfo on .NET Framework, whose TimeZoneInfo knows Windows ids only.
    internal static class ZonesGen
    {
        private static readonly Regex MapZone = new Regex(
            "<mapZone\\s+other=\"([^\"]+)\"\\s+territory=\"([^\"]+)\"\\s+type=\"([^\"]+)\"",
            RegexOptions.Compiled);

        internal static void Write(string xmlPath, string outPath)
        {
            var map = new SortedDictionary<string, string>(StringComparer.Ordinal);
            string version = "";
            foreach (string line in File.ReadLines(xmlPath))
            {
                if (line.Contains("<version number=") && version.Length == 0)
                    version = Regex.Match(line, "number=\"([^\"]+)\"").Groups[1].Value;
                Match m = MapZone.Match(line);
                if (!m.Success)
                    continue;
                string windows = m.Groups[1].Value;
                foreach (string iana in m.Groups[3].Value.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries))
                {
                    // the 001 (world) row is canonical; a territory row only fills a key the world row lacks
                    if (m.Groups[2].Value == "001" || !map.ContainsKey(iana))
                        map[iana] = windows;
                }
            }
            if (version.Length == 0 || version.Contains("$"))
                version = "main";   // the repository copy carries a $Revision$ placeholder, a release a number

            // windowsZones.xml names each zone by CLDR's canonical (older) IANA id; bcp47/timezone.xml
            // groups every alias of a zone (Asia/Calcutta Asia/Kolkata), so each group shares the mapping.
            string aliases = Path.Combine(Path.GetDirectoryName(xmlPath) ?? ".", "timezone.xml");
            int folded = 0;
            if (File.Exists(aliases))
            {
                var aliasAttr = new Regex("alias=\"([^\"]+)\"");
                foreach (string line in File.ReadLines(aliases))
                {
                    Match m = aliasAttr.Match(line);
                    if (!m.Success)
                        continue;
                    string[] names = m.Groups[1].Value.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
                    string windows = null;
                    foreach (string n in names)
                        if (map.TryGetValue(n, out windows))
                            break;
                    if (windows == null)
                        continue;
                    foreach (string n in names)
                    {
                        if (!map.ContainsKey(n))
                        {
                            map[n] = windows;
                            folded++;
                        }
                    }
                }
            }
            Console.WriteLine("  Zones: " + map.Count + " IANA keys (CLDR " + version + ", " + folded + " from aliases)");

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("//     Generated by tools/Outbridge.PyLite.UnicodeGen from CLDR windowsZones.xml (" + version + ").");
            sb.AppendLine("//     Do not edit by hand: re-run the generator instead (see its README).");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("namespace Outbridge.PyLite.Modules.Support");
            sb.AppendLine("{");
            sb.AppendLine("    internal static partial class WindowsZones");
            sb.AppendLine("    {");
            sb.AppendLine("        internal const string CldrVersion = \"" + version + "\";");
            sb.AppendLine();
            sb.AppendLine("        // IANA keys in ordinal order (binary-searched) and the Windows id of each.");
            sb.AppendLine("        private static readonly string[] Iana =");
            sb.AppendLine("        {");
            foreach (KeyValuePair<string, string> kv in map)
                sb.AppendLine("            \"" + kv.Key + "\",");
            sb.AppendLine("        };");
            sb.AppendLine();
            sb.AppendLine("        private static readonly string[] Windows =");
            sb.AppendLine("        {");
            foreach (KeyValuePair<string, string> kv in map)
                sb.AppendLine("            \"" + kv.Value + "\",");
            sb.AppendLine("        };");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            File.WriteAllText(outPath, sb.ToString(), new UTF8Encoding(false));
            Console.WriteLine("wrote " + outPath + " (" + new FileInfo(outPath).Length / 1024 + " KB)");
        }
    }
}
